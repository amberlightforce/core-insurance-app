/// <summary>
/// NX-EC-12: the regulatory go-live checklist. Every pack value, core default and clock that is not Settled/Verified is listed in
/// <c>docs/regulatory/go-live-checklist.md</c> (regenerated by this test, committed so a diff shows when the open set changes),
/// including every value resting on a secondary or unverified source. Also: the synthetic CY pack is refused in Production, and
/// structure-only golden tests of the GR levy lines (no levy amount is asserted, D-REG-06/06a).
/// </summary>
public sealed class RegulatoryGoLiveChecklistTests
{
    private static readonly Regex OpenQuestion = new(@"\b(?:OQ|OI)-[A-Z]*-?\d+\b", RegexOptions.CultureInvariant, TimeSpan.FromSeconds(1));
    private static readonly Regex SecondaryMarker = new(@"secondary[ _]source|peer-verified|market guidance", RegexOptions.CultureInvariant | RegexOptions.IgnoreCase, TimeSpan.FromSeconds(1));

    private static readonly LegalEntityInfo CyEntity = new(
        new LegalEntityId(Guid.Parse("0192f0c4-0000-7000-8000-0000000000c1")), LegalEntityCode.Parse("CY-TEST"), "CY", CyPack.PackId, "EUR", "Asia/Nicosia", "ACTIVE", true);

    private sealed record Row(string Area, string Item, string Value, string Status, string Source, string Open, bool Secondary);

    private static bool IsOpen(LegalStatus status) => status is not (LegalStatus.Settled or LegalStatus.NotRegulatory);

    private static string OpenRefs(params string?[] texts) =>
        string.Join(", ", texts.Where(t => t is not null).SelectMany(t => OpenQuestion.Matches(t!).Select(m => m.Value)).Distinct(StringComparer.Ordinal));

    private static IEnumerable<Row> PackRows(string area, IEnumerable<PackConfigValue> values) =>
        values.Where(v => IsOpen(v.LegalStatus)).Select(v => new Row(
            area, v.Key, Truncate(v.Value), v.LegalStatus.ToString(), v.SourceRef, OpenRefs(v.SourceRef, v.Note),
            v.LegalStatus is LegalStatus.Unverified or LegalStatus.Verify or LegalStatus.Uncertain or LegalStatus.MarketPractice
            || SecondaryMarker.IsMatch(v.SourceRef) || (v.Note is not null && SecondaryMarker.IsMatch(v.Note))));

    private static string Truncate(string text) => text.Length <= 60 ? text : text[..57] + "...";

    private static List<Row> Collect()
    {
        var rows = new List<Row>();
        rows.AddRange(PackRows("GR pack value", new GrPackConfiguration().Values));
        rows.AddRange(PackRows("Core default", CoreDefaults.Values));
        rows.AddRange(PackRows("CY pack value (SYNTHETIC, never Production)", new CyTreatmentRules().Values));

        // Registered keys no pack or default fills: absent values fail closed (D-REG-01) but still block go-live.
        var filled = new GrPackConfiguration().Values.Concat(CoreDefaults.Values).Select(v => v.Key).ToHashSet(StringComparer.Ordinal);
        foreach (var key in ConfigKeys.All.Where(k => !k.IsPrefix && k.Key.StartsWith("tax.", StringComparison.Ordinal) && !filled.Contains(k.Key)))
        {
            rows.Add(new Row("GR key with no value (fails closed)", key.Key, "(absent)", "Absent", key.Description, OpenRefs(key.Description), false));
        }

        foreach (var clock in ClockDefinitions.All.Where(c => c.LegalStatus != ClockLegalStatus.Verified))
        {
            rows.Add(new Row("Statutory clock", clock.Code, clock.Duration, clock.LegalStatus, clock.Source, OpenRefs(clock.Source),
                clock.LegalStatus is ClockLegalStatus.SecondarySource or ClockLegalStatus.Illustrative));
        }

        // Behaviour that is stubbed or placeholder, not a stored value.
        rows.Add(new Row("Fiscal channel", "myDATA document types, E3 codes, XSD version", MyDataStubFiscalChannel.UnmappedCode, "Stub", "MyDataStubFiscalChannel; never bound in Production", "OQ-012", false));
        rows.Add(new Row("Claims", "Friendly-settlement clearing eligibility", "(stub decisions)", "Unverified", "FriendlySettlementClearingStub (GR), unbound in Production; CLM-ERR-FS-DISABLED", "", true));
        rows.Add(new Row("Identifiers", "Vehicle plate validation (GR and CY)", "(format only)", "Unverified", "GreekVehiclePlate / CyIdValidator return Unverified with findings", "", true));
        rows.Add(new Row("Statutory clock", "CMP_COMPLAINT_ACK", "(not defined)", "Absent", "5 business days, UNVERIFIED; no value invented (fails closed)", "OI-CMP-06", true));
        return rows;
    }

    private static string Render(List<Row> rows)
    {
        var sb = new StringBuilder();
        sb.Append("# Regulatory go-live checklist\n\n");
        sb.Append("Generated by `RegulatoryGoLiveChecklistTests` (tests/CoreIns.CountryPacks.Tests); do not edit by hand. Every item below is not Settled/Verified and must be\n");
        sb.Append("closed (legal sign-off, then status raised in the pack) before Production activation (D-REG-02, REQ-MKT-343). Production refuses non-Settled pack values.\n\n");
        Table(sb, "Items still open", rows);
        Table(sb, "Secondary or unverified sources (re-verify against the primary text)", rows.Where(r => r.Secondary).ToList());
        return sb.ToString();
    }

    private static void Table(StringBuilder sb, string title, IReadOnlyCollection<Row> rows)
    {
        sb.Append(CultureInfo.InvariantCulture, $"## {title} ({rows.Count})\n\n| Area | Item | Value | Status | Open question | Source |\n|---|---|---|---|---|---|\n");
        foreach (var r in rows.OrderBy(r => r.Area, StringComparer.Ordinal).ThenBy(r => r.Item, StringComparer.Ordinal))
        {
            sb.Append(CultureInfo.InvariantCulture, $"| {Cell(r.Area)} | `{Cell(r.Item)}` | {Cell(r.Value)} | {r.Status} | {Cell(r.Open)} | {Cell(r.Source)} |\n");
        }

        sb.Append('\n');
    }

    private static string Cell(string text) => text.Replace("|", "/", StringComparison.Ordinal).Replace("\r", " ", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal);

    private static string OutputPath()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "CoreIns.sln")))
        {
            dir = dir.Parent;
        }

        var root = dir?.FullName ?? AppContext.BaseDirectory;
        return Path.Combine(root, "docs", "regulatory", "go-live-checklist.md");
    }

    [Fact]
    public void The_checklist_is_written_and_lists_the_known_open_items_including_the_complaint_reply_clock()
    {
        var rows = Collect();
        var text = Render(rows);
        var path = OutputPath();
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, text, new UTF8Encoding(false));

        File.Exists(path).ShouldBeTrue();
        rows.ShouldContain(r => r.Item == "tax.levy.auxfund.split_basis" && r.Status == "PendingOpinion");
        rows.ShouldContain(r => r.Item == "tax.ipt.liability_point" && r.Status == "PendingOpinion");
        rows.ShouldContain(r => r.Item == "tax.levy.auxfund.ph_stamp_duty_rate" && r.Status == "Absent");
        rows.ShouldContain(r => r.Item == "tax.levy.auxfund.split.insurer_share" && r.Status == "Absent");
        rows.ShouldContain(r => r.Item == "myDATA document types, E3 codes, XSD version");
        rows.ShouldContain(r => r.Item == ClockDefinitions.ClmFsCounterpartyReply && r.Status == ClockLegalStatus.Illustrative);

        // The 50-day complaint reply clock rests on a secondary source: it must be listed as open and as secondary.
        var complaint = rows.Single(r => r.Item == ClockDefinitions.ComplaintReply);
        complaint.Value.ShouldBe("P50D");
        complaint.Status.ShouldBe(ClockLegalStatus.SecondarySource);
        complaint.Secondary.ShouldBeTrue();
        text.ShouldContain("CMP_COMPLAINT_REPLY");

        // Nothing Verified or Settled leaks into the list.
        rows.Where(r => r.Area == "Statutory clock" && r.Item == ClockDefinitions.DsarResponse).ShouldBeEmpty();
        rows.Where(r => r.Item == "tax.ipt.rate.general").ShouldBeEmpty();
    }

    [Fact]
    public void Every_clock_without_a_Verified_status_is_on_the_checklist()
    {
        var items = Collect().Where(r => r.Area == "Statutory clock").Select(r => r.Item).ToHashSet(StringComparer.Ordinal);

        foreach (var clock in ClockDefinitions.All.Where(c => c.LegalStatus != ClockLegalStatus.Verified))
        {
            items.ShouldContain(clock.Code);
        }
    }

    [Fact]
    public async Task Production_refuses_the_synthetic_CY_pack_treatment_rows()
    {
        var clock = new ManualClock(Instant.FromUtc(2026, 10, 20));
        var catalogue = new ConfigurationCatalogue([new CyTreatmentRules()], clock.Now);
        var production = new ConfigurationEngine(catalogue, new LegalEntityRegistry([CyEntity]), new Env("Production"), clock);
        var development = new ConfigurationEngine(catalogue, new LegalEntityRegistry([CyEntity]), new Env("Development"), clock);
        TaxTreatmentRequest Request(TaxTransactionKind kind, TaxCategory category, string? source = null) => new()
        {
            LegalEntityId = CyEntity.Id.Value,
            RiskJurisdiction = "CY",
            TaxPointDate = new DateOnly(2027, 1, 15),
            ChargeType = "IPT",
            Category = category,
            ChargeOrigin = ChargeOrigin.Pol,
            TransactionKind = kind,
            CancellationSource = source,
            PolicyholderType = PolicyholderType.Consumer,
            BusinessBasis = "ESTABLISHMENT",
        };

        foreach (var request in new[]
                 {
                     Request(TaxTransactionKind.NewBusiness, TaxCategory.Tax),
                     Request(TaxTransactionKind.Refund, TaxCategory.Levy),
                     Request(TaxTransactionKind.Cancellation, TaxCategory.Stamp, "Policyholder"),
                 })
        {
            var refused = await Should.ThrowAsync<DomainException>(async () => await new MarketTaxCalculator(production).TreatmentAsync(request, TestContext.Current.CancellationToken));
            refused.Error.Code.ToString().ShouldBe("MKT-ERR-CFG-NOT-SETTLED");
            refused.Error.Detail!.ShouldContain("(Draft)");
            (await new MarketTaxCalculator(development).TreatmentAsync(request, TestContext.Current.CancellationToken)).Provisional.ShouldBeTrue();
        }

        new CyTreatmentRules().Values.ShouldAllBe(v => v.LegalStatus == LegalStatus.Draft);
        catalogue.Entries.Where(e => e.Node == "country:CY").ShouldAllBe(e => !e.IsSettled);
    }

    [Fact]
    public void GR_levy_lines_golden_structure_only()
    {
        var levy = new GrPackConfiguration().Values.Where(v => v.Key.StartsWith("tax.levy.", StringComparison.Ordinal)).OrderBy(v => v.Key, StringComparer.Ordinal).ToList();

        // The exact key set: the burden split (OQ-010), components, stamp duty and mid-term/cancellation treatment are deliberately absent.
        levy.Select(v => v.Key).ShouldBe(["tax.levy.auxfund.base", "tax.levy.auxfund.ceiling_rate", "tax.levy.auxfund.split_basis"]);
        levy.ShouldAllBe(v => v.LegalStatus == LegalStatus.PendingOpinion);
        levy.ShouldAllBe(v => v.MotorPath);
        levy.ShouldAllBe(v => !string.IsNullOrWhiteSpace(v.SourceRef));
        levy.ShouldAllBe(v => v.ValidFrom == null && v.ValidTo == null);

        var ceiling = levy.Single(v => v.Key.EndsWith("ceiling_rate", StringComparison.Ordinal));
        ceiling.Type.ShouldBe(ConfigValueType.ExactDecimal);
        decimal.TryParse(ceiling.Value, NumberStyles.Number, CultureInfo.InvariantCulture, out var rate).ShouldBeTrue();
        (rate > 0m && rate < 1m).ShouldBeTrue();

        levy.Single(v => v.Key.EndsWith("split_basis", StringComparison.Ordinal)).Type.ShouldBe(ConfigValueType.Text);
        levy.Single(v => v.Key.EndsWith(".base", StringComparison.Ordinal)).Type.ShouldBe(ConfigValueType.Text);

        // The treatment rows cover the IPT category only, plus (0.3.0, NX-HD-06) the levy lines of a distance-withdrawal void.
        new GrPackConfiguration().Values
            .Where(v => v.Key.StartsWith("tax.treatment.rule.", StringComparison.Ordinal) && !v.Key.StartsWith("tax.treatment.rule.TAX.", StringComparison.Ordinal))
            .Select(v => v.Key)
            .ShouldBe(["tax.treatment.rule.LEVY.VOID.DistanceWithdrawal", "tax.treatment.rule.LEVY.DISTANCE_WITHDRAWAL_VOID.ANY"], ignoreOrder: true);
    }

