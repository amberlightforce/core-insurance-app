import { CalendarDate } from '@internationalized/date';
import { describe, expect, it } from 'vitest';

import { isAcceleratorKey, parseDateInput } from './date-input';

// Wednesday 7 October 2026.
const today = new CalendarDate(2026, 10, 7);

function parse(text: string): string | null {
  return parseDateInput(text, { today })?.toString() ?? null;
}

describe('parseDateInput', () => {
  it.each([
    // words (accent- and case-insensitive)
    ['σ', '2026-10-07'],
    ['Σ', '2026-10-07'],
    ['σήμερα', '2026-10-07'],
    ['σημερα', '2026-10-07'],
    ['ΣΗΜΕΡΑ', '2026-10-07'],
    ['t', '2026-10-07'],
    ['today', '2026-10-07'],
    ['Today', '2026-10-07'],
    ['s', '2026-10-07'],
    ['α', '2026-10-08'],
    ['αύριο', '2026-10-08'],
    ['ΑΥΡΙΟ', '2026-10-08'],
    ['tomorrow', '2026-10-08'],
    ['a', '2026-10-08'],
    ['χθες', '2026-10-06'],
    ['χθές', '2026-10-06'],
    ['yesterday', '2026-10-06'],
    ['τμ', '2026-10-31'],
    ['ΤΜ', '2026-10-31'],
    ['τ.μ.', '2026-10-31'],
    ['eom', '2026-10-31'],
    ['tm', '2026-10-31'],
    ['αμ', '2026-10-01'],
    ['som', '2026-10-01'],
    // offsets
    ['+30', '2026-11-06'],
    ['+0', '2026-10-07'],
    ['-7', '2026-09-30'],
    ['\u22127', '2026-09-30'],
    ['+ 30', '2026-11-06'],
    ['+30d', '2026-11-06'],
    ['+10η', '2026-10-17'],
    ['+2w', '2026-10-21'],
    ['+2εβδ', '2026-10-21'],
    ['+6μ', '2027-04-07'],
    ['+6m', '2027-04-07'],
    ['+6 μήνες', '2027-04-07'],
    ['-1μ', '2026-09-07'],
    ['+1ε', '2027-10-07'],
    ['+1y', '2027-10-07'],
    ['+1 έτος', '2027-10-07'],
    ['-18y', '2008-10-07'],
    // separated dates
    ['7/10', '2026-10-07'],
    ['07/10', '2026-10-07'],
    ['7.10', '2026-10-07'],
    ['7-10', '2026-10-07'],
    ['7 10', '2026-10-07'],
    ['7.10.26', '2026-10-07'],
    ['7/10/2026', '2026-10-07'],
    ['7-10-2026', '2026-10-07'],
    ['07.10.2026', '2026-10-07'],
    ['1/1/27', '2027-01-01'],
    ['7.10.85', '1985-10-07'],
    ['31/12/1999', '1999-12-31'],
    ['29/2/2028', '2028-02-29'],
    // digits only
    ['07102026', '2026-10-07'],
    ['071026', '2026-10-07'],
    ['0710', '2026-10-07'],
    ['15', '2026-10-15'],
    ['1', '2026-10-01'],
  ])('%s → %s', (text, expected) => {
    expect(parse(text)).toBe(expected);
  });

  it.each([
    [''],
    ['   '],
    ['xyz'],
    ['31/2'],
    ['29/2/2027'],
    ['32/1/2026'],
    ['0/1/2026'],
    ['1/13/2026'],
    ['+5q'],
    ['++5'],
    ['7/10/202'],
    ['123'],
    ['12345'],
    ['1234567'],
    ['31/04/2026'],
    ['32'],
  ])('rejects %s', (text) => {
    expect(parse(text)).toBeNull();
  });

  it('crosses month and year boundaries', () => {
    expect(parseDateInput('+1', { today: new CalendarDate(2026, 12, 31) })?.toString()).toBe(
      '2027-01-01',
    );
    expect(parseDateInput('τμ', { today: new CalendarDate(2028, 2, 3) })?.toString()).toBe(
      '2028-02-29',
    );
    expect(parseDateInput('+1μ', { today: new CalendarDate(2026, 1, 31) })?.toString()).toBe(
      '2026-02-28',
    );
  });
});

describe('isAcceleratorKey', () => {
  it.each([
    ['σ', true],
    ['t', true],
    ['+', true],
    ['-', true],
    ['\u2212', true],
    ['5', false],
    ['/', false],
    ['Enter', false],
    ['ArrowUp', false],
    [' ', false],
  ])('%s → %s', (key, expected) => {
    expect(isAcceleratorKey(key)).toBe(expected);
  });
});
